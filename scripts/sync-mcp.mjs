#!/usr/bin/env node
// Repo-local MCP adapters. Resolved private endpoint names stay in ignored native files.
import { chmodSync, lstatSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OWNER = 'harness/scripts/sync-mcp.mjs'
const MARKER = `# Generated by ${OWNER}; edit .mcp.json and run make mcp.\n`
const ACCOUNT = 'MCP_CONNECTOR_ACCOUNT'
const isObject = (value) => value !== null && typeof value === 'object' && !Array.isArray(value)

function resolveUrl(value, account) {
  if (typeof value !== 'string' || !value || /[\s\\\u0000-\u001f\u007f]/.test(value)) throw new Error('MCP URL must be a plain HTTP(S) URL')
  const references = value.match(/\$\{[^}]*\}/g) ?? []
  if (references.some((reference) => reference !== `\${${ACCOUNT}}`) || value.replaceAll(`\${${ACCOUNT}}`, '').includes('$'))
    throw new Error(`Only the ${ACCOUNT} account-id placeholder is supported in MCP URLs`)
  let url = value
  if (references.length) {
    if (typeof account !== 'string' || !account) throw new Error(`${ACCOUNT} must be available in the environment`)
    if (!/^[a-zA-Z0-9-]+$/.test(account)) throw new Error(`${ACCOUNT} must be a hostname account identifier`)
    url = value.replaceAll(`\${${ACCOUNT}}`, account)
  }
  let parsed
  try {
    parsed = new URL(url)
  } catch {
    throw new Error('MCP URL must be a plain HTTP(S) URL')
  }
  if (!['http:', 'https:'].includes(parsed.protocol) || !parsed.hostname || parsed.username || parsed.password || parsed.search || parsed.hash)
    throw new Error('MCP URL must use HTTP(S) without userinfo, query, or fragment')
  return url
}

/**
 * Validate the workspace source and render native Codex and pi configuration.
 * @param {unknown} source Parsed .mcp.json; only HTTP type/url entries are supported.
 * @param {string | undefined} account Non-secret hostname account identifier, when referenced.
 * @returns {{path: string, content: string}[]} Deterministic native file contents.
 * @throws {Error} On unsupported declarations or missing/invalid account identifiers; values are never included.
 */
export function renderMcp(source, account) {
  if (!isObject(source) || Object.keys(source).some((key) => key !== 'mcpServers') || !isObject(source.mcpServers))
    throw new Error('.mcp.json must contain only an mcpServers object')
  const servers = {}
  const namespaces = new Set()
  let codex = MARKER
  for (const name of Object.keys(source.mcpServers).sort()) {
    if (!/^[a-zA-Z0-9_-]+$/.test(name)) throw new Error('MCP server names may contain only letters, digits, underscores, and hyphens')
    const namespace = name.replaceAll('-', '_')
    if (namespaces.has(namespace)) throw new Error('MCP server names collide after normalizing hyphens and underscores')
    namespaces.add(namespace)
    const server = source.mcpServers[name]
    if (!isObject(server) || Object.keys(server).some((key) => !['type', 'url'].includes(key)) || server.type !== 'http')
      throw new Error('MCP entries must contain only type: http and url; other fields and transports are unsupported')
    const url = resolveUrl(server.url, account)
    Object.defineProperty(servers, name, { value: { type: 'http', url }, enumerable: true })
    codex += `\n[mcp_servers.${JSON.stringify(name)}]\nurl = ${JSON.stringify(url)}\n`
  }
  return [
    { path: '.codex/config.toml', content: codex },
    { path: '.pi/mcp.json', content: JSON.stringify({ _generatedBy: OWNER, mcpServers: servers }, null, 2) + '\n' },
  ]
}

function readSource(root) {
  let source
  try {
    source = JSON.parse(readFileSync(join(root, '.mcp.json'), 'utf8'))
  } catch {
    throw new Error('Cannot read .mcp.json as JSON')
  }
  return source
}

function preflight(root, output) {
  const file = join(root, output.path)
  const folder = dirname(file)
  try {
    const parent = lstatSync(folder)
    if (parent.isSymbolicLink() || !parent.isDirectory()) throw new Error(`Refusing non-directory or symlink parent for ${output.path}`)
  } catch (error) {
    if (error.code !== 'ENOENT') throw error
  }
  // lstat also catches dangling links, which existsSync follows.
  let stat
  try {
    stat = lstatSync(file)
  } catch (error) {
    if (error.code === 'ENOENT') return
    throw new Error(`Cannot inspect ${output.path}`)
  }
  if (!stat.isFile() || stat.isSymbolicLink()) throw new Error(`Refusing non-file or symlink ${output.path}`)
  const content = readFileSync(file, 'utf8')
  let owned = content.startsWith(MARKER)
  if (output.path.endsWith('.json')) {
    try {
      const parsed = JSON.parse(content)
      owned = isObject(parsed) && parsed._generatedBy === OWNER
    } catch {
      owned = false
    }
  }
  if (!owned) throw new Error(`Refusing to overwrite unowned ${output.path}; preserve it before running make mcp`)
}

/**
 * Generate ignored native files after validating the source and both destinations.
 * @param {string} root Workspace directory containing .mcp.json.
 * @param {string | undefined} account Non-secret account identifier; never used for credentials.
 * @returns {void}
 * @throws {Error} If validation fails or a destination is not owned by this generator.
 */
export function syncMcp(root, account) {
  const outputs = renderMcp(readSource(root), account)
  for (const output of outputs) preflight(root, output)
  for (const output of outputs) {
    const file = join(root, output.path)
    mkdirSync(dirname(file), { recursive: true })
    writeFileSync(file, output.content, { mode: 0o600 })
    chmodSync(file, 0o600)
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href) {
  process.on('unhandledRejection', () => {
    console.error('Workspace MCP generation failed')
    process.exit(1)
  })
  try {
    const args = process.argv.slice(2)
    if (args.length === 1 && args[0] === '--check') {
      renderMcp(readSource(ROOT), 'example-account')
      console.log('Workspace MCP source is valid for Codex and pi (no local files read or written)')
    } else if (args.length === 0) {
      syncMcp(ROOT, process.env[ACCOUNT])
      console.log('Generated ignored workspace MCP configuration for Codex and pi')
    } else {
      throw new Error('Usage: sync-mcp.mjs [--check]')
    }
  } catch (error) {
    console.error(error instanceof Error ? error.message : 'Workspace MCP generation failed')
    process.exitCode = 1
  }
}
